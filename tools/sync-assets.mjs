#!/usr/bin/env node
// Syncs the asset library from the register (D-053). Reads the register with a read-only Google
// service account, copies every approved row with known rights from Drive into assets/library/,
// removes files whose rows are no longer approved, and writes _data/assets.yml.
// Usage: GOOGLE_SERVICE_ACCOUNT_KEY='<the account’s JSON key>' node tools/sync-assets.mjs
//   ASSET_REGISTER_ID  the register spreadsheet (default: the Grow Good asset register)
//   ASSET_SYNC_REPORT  a path to write the report to, as Markdown (the workflow’s pull request body)
// The GitHub workflow .github/workflows/assets.yml runs this and opens a pull request.

import { readFileSync, writeFileSync, mkdirSync, readdirSync, rmSync, existsSync, appendFileSync } from 'node:fs';
import { join } from 'node:path';
import { pathToFileURL } from 'node:url';
import { stringify } from 'yaml';
import { rowsFromValues, unusableReason, libraryName, imageSize, sizeProblem, manifestItem, buildManifest, LIBRARY, MANIFEST } from './lib/assets.mjs';
import { accessToken, sheetValues, driveFile } from './lib/google.mjs';

export const REGISTER_ID = '1KH1aZgWdh7mh1G72m4zsZ55CJTiZH_fFFny2-CxJt0w';
export const REGISTER_RANGE = 'Register!A1:R';
const HEADER = '# Generated by tools/sync-assets.mjs from the asset register (D-053). Do not edit: change the register, then sync.\n';

export async function sync({ key, registerId = REGISTER_ID, root = '.', fetchImpl = fetch } = {}) {
  const token = await accessToken(key, { fetchImpl });
  const rows = rowsFromValues(await sheetValues(token, registerId, REGISTER_RANGE, { fetchImpl }));
  const libraryDir = join(root, LIBRARY);
  mkdirSync(libraryDir, { recursive: true });

  const items = [];
  const skipped = []; // approved rows that could not go in
  const waiting = []; // draft rows, for the count
  const kept = new Set();
  const changed = [];
  for (const row of rows) {
    const reason = unusableReason(row);
    if (reason) {
      (row.status === 'approved' ? skipped : waiting).push({ id: row.asset_id, reason });
      continue;
    }
    const file = libraryName(row);
    const buf = await driveFile(token, row.drive_file_id, { fetchImpl });
    const size = imageSize(buf);
    const problem = sizeProblem(size, buf.length);
    if (problem) { skipped.push({ id: row.asset_id, reason: problem }); continue; }
    const path = join(libraryDir, file);
    if (!existsSync(path) || !readFileSync(path).equals(buf)) { writeFileSync(path, buf); changed.push(file); }
    kept.add(file);
    items.push(manifestItem(row, file, size));
  }
  const removed = readdirSync(libraryDir).filter((f) => !f.startsWith('.') && !kept.has(f));
  for (const f of removed) rmSync(join(libraryDir, f));

  mkdirSync(join(root, '_data'), { recursive: true });
  // Plain YAML: each logo is written out in full, not as an alias of its item, so every reader gets the same data.
  writeFileSync(join(root, MANIFEST), HEADER + stringify(buildManifest(items), { lineWidth: 0, aliasDuplicateObjects: false }));
  return { rows: rows.length, items, changed, removed, skipped, waiting };
}

export function report(r) {
  const lines = [
    `Synced the asset library from the register (D-053): ${r.items.length} approved ${r.items.length === 1 ? 'asset' : 'assets'} of ${r.rows} rows.`,
    '',
    r.changed.length ? `- New or changed: ${r.changed.map((f) => `\`${f}\``).join(', ')}` : '- No new or changed files.',
    r.removed.length ? `- Removed, no longer approved: ${r.removed.map((f) => `\`${f}\``).join(', ')}` : null,
    r.waiting.length ? `- Not yet approved: ${r.waiting.length} ${r.waiting.length === 1 ? 'row' : 'rows'}.` : null,
  ].filter((l) => l !== null);
  if (r.skipped.length) {
    lines.push('', 'Approved but left out, to fix in the register or Drive:', '', ...r.skipped.map((s) => `- ${s.id || '(no id)'}: ${s.reason}`));
  }
  return `${lines.join('\n')}\n`;
}

async function main() {
  const raw = process.env.GOOGLE_SERVICE_ACCOUNT_KEY;
  if (!raw) { console.error('GOOGLE_SERVICE_ACCOUNT_KEY is not set: the sync needs the read-only service account’s JSON key (asset-library/README.md).'); process.exit(1); }
  const r = await sync({ key: JSON.parse(raw), registerId: process.env.ASSET_REGISTER_ID || REGISTER_ID });
  const text = report(r);
  console.log(text);
  if (process.env.ASSET_SYNC_REPORT) writeFileSync(process.env.ASSET_SYNC_REPORT, text);
  if (process.env.GITHUB_STEP_SUMMARY) appendFileSync(process.env.GITHUB_STEP_SUMMARY, `### Asset sync\n\n${text}`);
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  main().catch((e) => { console.error(e.message); process.exit(1); });
}
