#!/usr/bin/env node
// Builds four-level color ramps from the seed palette (decision D-021).
// Usage: node tools/build-ramps.mjs [seed] [out]
// Defaults: tokens/seed/from-sass.json  tokens/seed/color-ramps.json
//
// Levels: 100 lightest; 200 bright accent; 300 dark; 400 darkest.
// Rule: every family's 100 reaches 4.5:1 on every family's 300 and 400.
// Existing values are kept where they fit, otherwise moved in lightness only
// (hue and chroma held in OKLCH). Missing levels are made from the family hue.

import { readFileSync, writeFileSync } from 'node:fs';
import { luminance, ratio, hexToOklch, oklchToHex, atLuminance } from './lib/color.mjs';

const seedFile = process.argv[2] ?? 'tokens/seed/from-sass.json';
const outFile = process.argv[3] ?? 'tokens/seed/color-ramps.json';
const seed = JSON.parse(readFileSync(seedFile, 'utf8')).color;
const MIN = 4.5;
const MARGIN = 4.6;

// Which existing value seeds which level.
const ANCHORS = {
  neutral: { 100: 'X', 200: 'XX', 400: 'XXX' },
  green: { 100: 'X', 200: 'XX', 400: 'XXX' },
  red: { 200: 'X', 300: 'XX' },
  gold: { 200: 'X', 300: 'XX' },
  purple: { 200: 'X', 300: 'XX', 400: 'XXX' },
};

// Values a person chose after review. They replace the kept or generated value
// and are never recomputed.
const CHOSEN = {
  purple: { 200: { hex: '#947cff', why: 'Option A on the color ramps page, chosen by Brad Nagle 2026-11-13 (D-021)' } },
};

// ---- build -----------------------------------------------------------------
const ramps = {};
for (const [family, map] of Object.entries(ANCHORS)) {
  const ref = hexToOklch(seed[family][map[200] ?? map[100]].$value); // hue source
  const isNeutral = family === 'neutral';
  ramps[family] = {};
  for (const level of [100, 200, 300, 400]) {
    const old = map[level];
    const hex = old ? seed[family][old].$value : null;
    ramps[family][level] = { hex, was: old ? `${family}.${old} ${hex}` : null, status: old ? 'kept' : 'new', ref };
  }
  // New 100: pale tint of the hue.
  if (!ramps[family][100].hex) {
    ramps[family][100].hex = atLuminance({ L: 0.95, C: isNeutral ? 0.006 : Math.min(ref.C * 0.22, 0.035), H: ref.H }, 0.8);
  }
  for (const [level, pick] of Object.entries(CHOSEN[family] ?? {})) {
    Object.assign(ramps[family][level], { hex: pick.hex, status: 'chosen', why: pick.why });
  }
}

// The dark ceiling every 300 must sit under, from the dimmest 100.
const minY100 = Math.min(...Object.values(ramps).map((r) => luminance(r[100].hex)));
const maxY300 = (minY100 + 0.05) / MARGIN - 0.05;

for (const [family, r] of Object.entries(ramps)) {
  const isNeutral = family === 'neutral';
  // 300: keep if dark enough, else darken in place; make one if missing.
  if (r[300].hex && luminance(r[300].hex) > maxY300) {
    r[300].hex = atLuminance(hexToOklch(r[300].hex), Math.min(maxY300, 0.11));
    r[300].status = 'adjusted';
  } else if (!r[300].hex) {
    r[300].hex = atLuminance({ L: 0.4, C: isNeutral ? 0.008 : Math.min(r[300].ref.C * 0.55, 0.1), H: r[300].ref.H }, Math.min(maxY300, 0.1));
  }
  // 400: must be clearly darker than 300 (OKLab L at least 0.08 lower).
  const L300 = hexToOklch(r[300].hex).L;
  if (r[400].hex && hexToOklch(r[400].hex).L > L300 - 0.08) {
    const lch = hexToOklch(r[400].hex);
    r[400].hex = oklchToHex({ ...lch, L: L300 - 0.1 });
    r[400].status = 'adjusted';
  } else if (!r[400].hex) {
    r[400].hex = oklchToHex({ L: Math.min(0.3, L300 - 0.1), C: isNeutral ? 0.006 : Math.min(r[400].ref.C * 0.3, 0.06), H: r[400].ref.H });
  }
}

// ---- verify ----------------------------------------------------------------
const fails = [];
const families = Object.keys(ramps);
for (const f of families) for (const g of families) for (const lv of [300, 400]) {
  const x = ratio(ramps[f][100].hex, ramps[g][lv].hex);
  if (x < MIN) fails.push(`${f}-100 on ${g}-${lv}: ${x.toFixed(2)}`);
}
const order = families.filter((f) => !(luminance(ramps[f][100].hex) > luminance(ramps[f][200].hex) && luminance(ramps[f][200].hex) > luminance(ramps[f][300].hex) && luminance(ramps[f][300].hex) > luminance(ramps[f][400].hex)));

// ---- write -----------------------------------------------------------------
const color = { $type: 'color' };
const migration = {};
for (const [f, r] of Object.entries(ramps)) {
  color[f] = {};
  for (const lv of [100, 200, 300, 400]) {
    const e = r[lv];
    color[f][lv] = {
      $value: e.hex,
      $extensions: { 'com.growgood.status': e.status, ...(e.was && { 'com.growgood.was': e.was }), ...(e.why && { 'com.growgood.why': e.why }), 'com.growgood.luminance': Math.round(luminance(e.hex) * 1000) / 1000 },
    };
    if (e.was) migration[e.was.split(' ')[0]] = `${f}-${lv}`;
  }
}
writeFileSync(outFile, JSON.stringify({
  $description: 'Four-level color ramps (D-021). Generated by tools/build-ramps.mjs from the Sass seed. Proposed values, not yet in Figma.',
  $extensions: { 'com.growgood.rule': `every 100 >= ${MIN}:1 on every 300 and 400`, 'com.growgood.migration': migration },
  color,
}, null, 2) + '\n');

console.log(`wrote ${outFile}`);
console.log(`dimmest 100 luminance ${minY100.toFixed(3)}; 300 ceiling ${maxY300.toFixed(3)}`);
for (const [f, r] of Object.entries(ramps)) {
  console.log(f.padEnd(8), [100, 200, 300, 400].map((lv) => `${lv} ${r[lv].hex} ${r[lv].status.padEnd(8)}`).join('  '));
}
console.log(`cross-family 100 on 300/400 failures: ${fails.length}${fails.length ? '\n  ' + fails.join('\n  ') : ''}`);
console.log(`families out of light-to-dark order: ${order.length ? order.join(', ') : 'none'}`);
for (const f of families) {
  console.log(`${f}: 200 on 400 ${ratio(ramps[f][200].hex, ramps[f][400].hex).toFixed(2)}, 400 on 100 ${ratio(ramps[f][400].hex, ramps[f][100].hex).toFixed(2)}, 100 on 300 ${ratio(ramps[f][100].hex, ramps[f][300].hex).toFixed(2)}`);
}
