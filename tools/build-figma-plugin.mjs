#!/usr/bin/env node
// Bundles the GG Tokens Figma plugin into figma-plugin/dist.
// Usage: node tools/build-figma-plugin.mjs
//   dist/code.js  = the repo's token files (as TOKENS) + tools/lib/tokens.mjs + src/code.js
//   dist/ui.html  = src/ui.html with tools/lib/tokens.mjs inlined
// Fails if dist/code.js uses syntax newer than ES2017, which the Figma sandbox may not run.

import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { parse } from 'acorn';
import { TOKEN_FILES } from './lib/tokens.mjs';

const HEADER = '// Generated by tools/build-figma-plugin.mjs. Do not edit: change figma-plugin/src or tools/lib/tokens.mjs, then rebuild.';
const lib = readFileSync('tools/lib/tokens.mjs', 'utf8').replace(/^export /gm, '');
const tokens = Object.fromEntries(TOKEN_FILES.map((f) => [f, JSON.parse(readFileSync(`tokens/${f}`, 'utf8'))]));

const code = [HEADER, `const TOKENS = ${JSON.stringify(tokens)};`, lib, readFileSync('figma-plugin/src/code.js', 'utf8')].join('\n');
try {
  parse(code, { ecmaVersion: 2017, sourceType: 'script' });
} catch (e) {
  const line = code.split('\n')[e.loc.line - 1];
  console.error(`dist/code.js is not ES2017 at line ${e.loc.line}: ${e.message}\n  ${line.trim()}`);
  process.exit(1);
}

const uiSource = readFileSync('figma-plugin/src/ui.html', 'utf8');
if (!uiSource.includes('/*SHARED*/')) throw new Error('figma-plugin/src/ui.html is missing the /*SHARED*/ placeholder');
const ui = `<!-- ${HEADER.slice(3)} -->\n` + uiSource.replace('/*SHARED*/', () => lib);

mkdirSync('figma-plugin/dist', { recursive: true });
writeFileSync('figma-plugin/dist/code.js', code);
writeFileSync('figma-plugin/dist/ui.html', ui);
console.log(`built figma-plugin/dist: code.js (${(code.length / 1024).toFixed(1)}KB, ES2017 ok), ui.html (${(ui.length / 1024).toFixed(1)}KB)`);
